create table if not exists public.guest_wishes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  status text not null check (char_length(status) between 1 and 120),
  wish text not null check (char_length(wish) between 1 and 1000),
  created_at timestamptz not null default now()
);

alter table public.guest_wishes enable row level security;

drop policy if exists "Anyone can read guest wishes" on public.guest_wishes;
create policy "Anyone can read guest wishes"
  on public.guest_wishes for select to anon using (true);

drop policy if exists "Anyone can add guest wishes" on public.guest_wishes;
create policy "Anyone can add guest wishes"
  on public.guest_wishes for insert to anon
  with check (
    char_length(name) between 1 and 120 and
    char_length(status) between 1 and 120 and
    char_length(wish) between 1 and 1000
  );

grant select, insert on public.guest_wishes to anon;
grant usage, select on sequence public.guest_wishes_id_seq to anon;
